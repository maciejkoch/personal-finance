import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { root, writeVersion } from "./write-version.mjs";

const [action, target = "production", ...args] = process.argv.slice(2);
if (!["serve", "build"].includes(action))
  throw new Error("Expected serve or build");
if (!["local", "production", "staging"].includes(target))
  throw new Error("Unknown API target");

if (target === "staging") {
  const value = process.env.OSZCZEDZIFY_STAGING_FUNCTIONS_BASE_URL;
  if (!value)
    throw new Error(
      "Set OSZCZEDZIFY_STAGING_FUNCTIONS_BASE_URL; staging never falls back to production.",
    );
  const base = new URL(value);
  if (
    base.protocol !== "https:" ||
    base.username ||
    base.password ||
    base.search ||
    base.hash
  ) {
    throw new Error(
      "Staging requires an HTTPS base URL without credentials, query or fragment.",
    );
  }
  if (
    base.hostname.endsWith("-personal-finance-2ee61.cloudfunctions.net") ||
    base.hostname.endsWith("-4mtb3gtbjq-uc.a.run.app")
  ) {
    throw new Error(
      "Use a separate staging backend, not the production Functions project.",
    );
  }
  const prefix = base.href.replace(/\/$/, "");
  const apiEndpoints = Object.fromEntries(
    Object.entries({
      savings: "calculateSavingsWarsaw",
      regularContribution: "calculateRegularContributionWarsaw",
      treasuryBonds: "calculateTreasuryBondsWarsaw",
      article: "articleWarsaw",
    }).map(([key, name]) => [key, `${prefix}/${name}`]),
  );
  writeFileSync(
    resolve(root, "src/environments/environment.staging.local.ts"),
    `// Generated by scripts/workspace.mjs. Do not edit.\nexport const environment = ${JSON.stringify({ apiEndpoints, seoIndexable: false }, null, 2)};\n`,
  );
}

if (action === "build") {
  const prepared = spawnSync(
    process.execPath,
    [resolve(root, "scripts/prepare-seo.mjs")],
    { cwd: root, stdio: "inherit" },
  );
  if (prepared.status !== 0) process.exit(prepared.status ?? 1);
}

writeVersion("frontend", target);
const configuration =
  action === "serve"
    ? {
        local: "development",
        production: "production-api",
        staging: "staging",
      }[target]
    : { local: "development", production: "production", staging: "staging" }[
        target
      ];
const ngArgs = [
  action,
  "personal-finance",
  `--configuration=${configuration}`,
  ...args,
];
const result = spawnSync(
  process.execPath,
  [resolve(root, "node_modules/@angular/cli/bin/ng.js"), ...ngArgs],
  {
    cwd: root,
    stdio: "inherit",
  },
);
if (result.error) throw result.error;
if (result.status === 0 && action === "build") {
  const finalized = spawnSync(
    process.execPath,
    [resolve(root, "scripts/finalize-hosting.mjs")],
    { cwd: root, stdio: "inherit" },
  );
  if (finalized.status !== 0) process.exit(finalized.status ?? 1);
}
process.exit(result.status ?? 1);
